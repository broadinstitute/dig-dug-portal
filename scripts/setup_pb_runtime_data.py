def download(host, relative, destination):
    ssh = 'ssh -T -o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=yes -o LogLevel=ERROR -o ServerAliveInterval=15 -o ServerAliveCountMax=2'
    result = subprocess.run([
        'rsync', '--partial', '--timeout=120', '-e', ssh,
        host + ':' + REMOTE + '/' + relative, str(destination),
    ])
    if result.returncode:
        raise RuntimeError('Download failed. Check VPN, SSH access and shared-group permissions; rerun to resume.')


def prepare(repo, manifest, host='e3', verify_only=False, transfer=download):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.@:-]*', host):
        raise ValueError('Use an SSH host or configured alias, such as e3 or your-login@e3-host.')
    repo = Path(repo).resolve()
    root = safe_path(repo, '.pb-private-data')
    entries = load_entries(manifest)
    for entry in entries:
        safe_path(root, entry['path'])
        safe_path(root, '.runtime-downloads/' + entry['path'])
    config = safe_path(root, 'local.env')
    if not verify_only and config.exists() and not config.read_text().startswith(HEADER):
        raise ValueError('Existing .pb-private-data/local.env is not installer-managed; preserve it and move it aside before setup.')
    if verify_only:
        missing = [e['path'] for e in entries if not matches(safe_path(root, e['path']), e)]
        if missing:
            raise RuntimeError('Missing or mismatched runtime files: ' + ', '.join(missing))
        print(f"Verified {len(entries)} runtime files against the repository manifest.")
        return root
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    lock_path = safe_path(root, '.runtime-setup.lock')
    with lock_path.open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        for number, entry in enumerate(entries, 1):
            target = safe_path(root, entry['path'])
            if matches(target, entry):
                print(f"[{number}/{len(entries)}] Verified: {entry['path']}", flush=True)
                continue
            staged = safe_path(root, '.runtime-downloads/' + entry['path'])
            staged.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
            print(f"[{number}/{len(entries)}] Downloading: {entry['path']}", flush=True)
            transfer(host, entry['path'], staged)
            if not matches(staged, entry):
                staged.unlink(missing_ok=True)
                raise RuntimeError('Checksum mismatch; file was not installed: ' + entry['path'])
            target.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
            staged.chmod(0o600)
            os.replace(staged, target)
        temporary = safe_path(root, '.local.env.tmp')
        temporary.write_text(environment(root, host))
        temporary.chmod(0o600)
        os.replace(temporary, config)
    print('Runtime files verified; local settings saved to .pb-private-data/local.env.', flush=True)
    return root


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ssh-host', default=os.environ.get('PB_CONTEXT_SSH_HOST', 'e3'))
    parser.add_argument('--verify-only', action='store_true', help='Verify the runtime files without downloading or changing settings.')
    args = parser.parse_args()
    os.umask(0o077)
    try:
        if not args.verify_only:
            for command in ('ssh', 'rsync'):
                if not shutil.which(command):
                    raise RuntimeError('Required command is not installed: ' + command)
        root = prepare(REPO, MANIFEST, args.ssh_host, args.verify_only)
        if not args.verify_only:
            env = dict(os.environ, PB_GT_AUTO_DOWNLOAD='0', PB_GT_SSH_HOST=args.ssh_host)
            env['PB_GENOTYPE_INDEX'] = str(root / 'genotypes/shared/2025_crdc_16366_dp20_af001_20260907/index')
            subprocess.run([sys.executable, str(REPO / 'scripts/setup_pb_genotypes.py')], env=env, check=True)
            print('Setup complete. Follow docs/pb_local_browser_setup.md to connect and open the browser.')
        return 0
    except (OSError, ValueError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
        print('Runtime setup: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
