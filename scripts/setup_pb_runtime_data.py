REPO = Path(__file__).resolve().parents[1]
MANIFEST = REPO / 'configs/pb_runtime_data_manifest.json'
REMOTE = '/lab-share/RC-Data-Science-e2/Groups/gnomad/kyuryung/share/dig-dug-portal/prototype_runtime_data'
HEADER = '# Generated by scripts/setup_pb_runtime_data.py\n'


def digest(path):
    value = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            value.update(block)
    return value.hexdigest()


def safe_path(root, relative):
    parts = PurePosixPath(relative).parts
    if (not parts or PurePosixPath(relative).is_absolute() or '..' in parts
            or not re.fullmatch(r'[A-Za-z0-9_./-]+', relative)
            or str(PurePosixPath(relative)) != relative):
        raise ValueError('Invalid runtime release path: ' + relative)
    current = root
    for part in parts:
        current = current / part
        if current.is_symlink():
            raise ValueError('Runtime paths must not contain symlinks: ' + str(current))
    return current


def load_entries(manifest):
    data = json.loads(Path(manifest).read_text())
    if data.get('schema') != 'pb-prototype-runtime-data-v1' or not data.get('files'):
        raise ValueError('Unsupported or empty runtime manifest.')
    seen = set()
    for entry in data['files']:
        path = entry['path']
        safe_path(Path('/unused'), path)
        if path in seen or not isinstance(entry['size_bytes'], int) or entry['size_bytes'] < 0:
            raise ValueError('Invalid or duplicate runtime manifest entry.')
        if not re.fullmatch(r'[0-9a-f]{64}', entry['sha256']):
            raise ValueError('Invalid runtime checksum.')
        seen.add(path)
    return data['files']


def matches(path, entry):
    return path.is_file() and path.stat().st_size == entry['size_bytes'] and digest(path) == entry['sha256']


