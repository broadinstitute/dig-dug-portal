    const samples=Array.from({length:20000},(_,index)=>({id:'SAMPLE-'+String(index+1).padStart(5,'0')}));
    const variant={id:'chr1:1:A:G',carrierSamples:samples,carrierCount:samples.length};
    const page=new Vue({mixins:[mixin],data:()=>({liveDataLoaded:true,geneInfo:{symbol:'GJB2'},variantRows:[variant],expandedVariantId:variant.id}),methods:{fetchVisibleCarrierSampleDetails(id){const row=this.variantRows.find(row=>row.id===id);requests.push(this.visibleCarrierRows(row).map(sample=>sample.id));},carrierSampleField(sample,field){return sample[field];}}});
    assert.equal(page.matchingCarrierSamples.length,20000);
    assert.equal(page.currentCarrierTableRows.length,5);
    assert.equal(page.carrierTablePageCount,4000);
    assert.equal(requests[0].length,5,'Opening a large variant requests only the first metadata page');
    page.goToCarrierTablePage(2);await Vue.nextTick();
    assert.equal(page.currentCarrierTableRows[0].id,'SAMPLE-00006');
    assert.equal(requests[requests.length-1].length,5);
    assert.equal(new Set(requests.flat()).size,10,'Page navigation must not fetch the whole carrier list');
    page.carrierTableSearch='SAMPLE-19999';await Vue.nextTick();
