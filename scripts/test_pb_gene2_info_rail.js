const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const babel = require('@babel/core');
const compiler = require('vue-template-compiler');
const {infoRailPosition} = require('../src/views/PbGene2/infoRailPosition');
const base = {shell:{left:200,right:1000,top:100,width:800},shellWidth:1000,anchor:{top:300,bottom:320},viewportWidth:1300};
let result = infoRailPosition(base);
assert.equal(result.layout,'right');
assert.equal(result.left,1016);
assert.equal(result.top,250,'CSS zoom is accounted for in the same shell coordinate space');
result=infoRailPosition({...base,anchor:{top:700,bottom:720}});
assert.equal(result.top,750,'Explanation remains level with the selected icon rather than moving above other tables');
result=infoRailPosition({...base,shell:{left:300,right:1100,top:100,width:800},viewportWidth:1150});
assert.equal(result.layout,'left');
assert.ok(result.left<0);
result=infoRailPosition({...base,shell:{left:20,right:1180,top:100,width:1160},shellWidth:1450,viewportWidth:1200});
assert.equal(result.layout,'reserve','A narrow desktop reserves room instead of covering a table');
result=infoRailPosition({...base,shell:{left:10,right:390,top:100,width:380},shellWidth:475,viewportWidth:400,card:{bottom:700}});
assert.equal(result.layout,'inline','Small screens put information after the relevant card with a reserved flow gap');
assert.equal(result.top,762);
const script = compiler.parseComponent(fs.readFileSync('src/views/PbGene2/InfoRail.vue','utf8')).script.content;
const compiled = babel.transformSync(script,{babelrc:false,configFile:false,plugins:['@babel/plugin-transform-modules-commonjs']}).code;
const exported = {};
vm.runInNewContext(compiled,{exports:exported,require:()=>({infoRailPosition}),window:{innerWidth:1300,innerHeight:900},clearTimeout,setTimeout});
const options = exported.default;
const events = [];
const rail = {...options.data(),$root:{$emit:(...args)=>events.push(args)},$emit(){},$nextTick:fn=>fn(),$refs:{panel:{offsetHeight:100,contains:()=>false}}};
for(const [name, fn] of Object.entries(options.methods)) rail[name]=fn.bind(rail);
const shell={offsetWidth:1000,getBoundingClientRect:()=>base.shell};
const anchor={isConnected:true,getBoundingClientRect:()=>base.anchor,closest:name=>name==='.pbg-shell'?shell:null,contains:()=>false};
const info={id:'one',label:'q',text:'Gene-wise BH definition',anchor,pin:false};
rail.open(info);
assert.equal(rail.placement.top,250);
assert.equal(rail.pinned,false);
rail.leave('one');rail.open({...info,pin:true});
assert.equal(rail.pinned,true,'Click keeps information open after leaving the icon');
rail.leave('one');assert.equal(rail.current.id,'one');
rail.open({...info,pin:true});assert.equal(rail.current,null,'Clicking the same pinned icon closes it');
rail.open(info);rail.keydown({key:'Escape'});assert.equal(rail.current,null);
rail.open(info);rail.outside({target:{}});assert.equal(rail.current,null);
console.log('Gene2 information rail: CSS zoom, same-height placement, side selection and non-overlapping fallbacks PASS');
